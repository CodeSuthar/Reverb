const {
    EmbedBuilder,
    ChannelType,
    PermissionFlagsBits,
    ActionRowBuilder,
    ButtonBuilder,
    ButtonStyle,
} = require("discord.js");

module.exports = {
    name: "createinvite",
    description: "Generate an instant invite link for a specified server.",
    usage: "<guildId>",
    category: "developer",
    developerOnly: true,
    aliases: ["ci", "gi", "ginvite", "guildinvite"],
    run: async (message, args, client, prefix) => {
        const guildId = args[0]?.trim();

        if (!guildId) {
            const emb = new EmbedBuilder()
                .setColor("Red")
                .setDescription(
                    `${client.emojiList.cross} | **Please provide the guild ID.**\nUsage: \`${prefix}createinvite <guildId>\``,
                );

            return message.reply({ embeds: [emb] });
        }

        try {
            const guild = client.guilds.cache.get(guildId) || (await client.guilds.fetch(guildId).catch(() => null));

            if (!guild) {
                const emb = new EmbedBuilder()
                    .setColor("Red")
                    .setDescription(
                        `${client.emojiList.cross} | **Guild not found.** Make sure the bot is currently in the server with ID \`${guildId}\`.`,
                    );

                return message.reply({ embeds: [emb] });
            }

            const me = guild.members.me || (await guild.members.fetchMe().catch(() => null));
            if (!me) {
                const emb = new EmbedBuilder()
                    .setColor("Red")
                    .setDescription(
                        `${client.emojiList.cross} | **Could not resolve the bot's membership in \`${guild.name}\`.**`,
                    );

                return message.reply({ embeds: [emb] });
            }

            // Find a suitable text channel where the bot has permission to create invites
            const channels = await guild.channels.fetch().catch(() => guild.channels.cache);
            const targetChannel = channels.find((channel) => {
                if (!channel) return false;
                const isText = channel.type === ChannelType.GuildText || channel.type === ChannelType.GuildAnnouncement;
                if (!isText) return false;
                const perms = channel.permissionsFor(me);
                return perms?.has([
                    PermissionFlagsBits.CreateInstantInvite,
                    PermissionFlagsBits.ViewChannel,
                ]);
            });

            if (!targetChannel) {
                const emb = new EmbedBuilder()
                    .setColor("Red")
                    .setDescription(
                        `${client.emojiList.cross} | **No channel found in \`${guild.name}\` where the bot has permission to create an invite.**`,
                    );

                return message.reply({ embeds: [emb] });
            }

            const invite = await targetChannel.createInvite({
                maxAge: 3600, // 1 hour
                maxUses: 0,   // unlimited during the hour
                reason: `Generated by developer: ${message.author.tag || message.author.username}`,
            });

            const linkButton = new ButtonBuilder()
                .setLabel(`Join ${guild.name}`)
                .setStyle(ButtonStyle.Link)
                .setURL(invite.url);

            const row = new ActionRowBuilder().addComponents(linkButton);

            const emb = new EmbedBuilder()
                .setColor(client?.color?.hex ?? "#FF66C4")
                .setDescription(
                    `${client.emojiList.tick} | **Successfully generated invite for \`${guild.name}\`:**\n${invite.url}`,
                )
                .addFields([
                    {
                        name: "Channel",
                        value: `${targetChannel} (\`${targetChannel.id}\`)`,
                        inline: true,
                    },
                    {
                        name: "Members",
                        value: `\`${guild.memberCount}\``,
                        inline: true,
                    },
                    {
                        name: "Expires In",
                        value: "`1 hour`",
                        inline: true,
                    },
                ])
                .setTimestamp();

            return message.reply({ embeds: [emb], components: [row] });
        } catch (err) {
            console.error("Error creating invite:", err);
            const emb = new EmbedBuilder()
                .setColor("Red")
                .setDescription(
                    `${client.emojiList.cross} | **An error occurred while generating the invite link.**`,
                );

            return message.reply({ embeds: [emb] });
        }
    },
};
